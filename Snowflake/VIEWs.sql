CREATE SCHEMA MY_VIEWS

-- SELECT DATA 
SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF100.NATION
SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF100.CUSTOMER LIMIT 50

-- JOIN 
SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF100.CUSTOMER AS C
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF100.NATION AS N
ON C.C_NATIONKEY = N.N_NATIONKEY
WHERE N.N_NAME = 'BRAZIL';

-- VIEW 
CREATE OR REPLACE VIEW  AVD.MY_VIEWS.CUSTOMER_VIEW
AS
    SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF100.CUSTOMER AS C
    JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF100.NATION AS N
    ON C.C_NATIONKEY = N.N_NATIONKEY
    WHERE N.N_NAME = 'BRAZIL';

-- DISPLAY VIEW 
SELECT * FROM AVD.MY_VIEWS.CUSTOMER_VIEW;
-- DISPLAY VIEW IN SCHMEA TOTAL VIEW 
SHOW VIEWS IN SCHEMA MY_VIEWS
