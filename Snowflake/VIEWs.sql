CREATE OR REPLACE MATERIALIZED VIEW AVD.MY_VIEWS.CUSTOMER_MATERIALIZED_VIEW
AS
    SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF100.ORDERS
    WHERE SUBSTR(O_ORDERPRIORITY, 1, 1) = '2'
    AND YEAR(O_ORDERDATE) = 1992 AND MONTH(O_ORDERDATE) = 7;
    

SELECT * FROM AVD.MY_VIEWS.CUSTOMER_MATERIALIZED_VIEW
